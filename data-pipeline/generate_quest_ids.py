#!/usr/bin/env python3
"""Generate site/js/services/quest-ids.js from the 2009Scape server source.

Saves store quests as {questId, questStage} where questId is Quest.index (the second
constructor argument of each Quest subclass). Display names come from content/data/Quests.kt.
Only quests that have a Quest subclass can appear in a save.

Usage: generate_quest_ids.py --source-root <upstream repo root> --source-commit <sha> [--output site/js/services/quest-ids.js]
"""
import argparse
import json
import re
from pathlib import Path

MAIN = "Server/src/main/"


def parse(root):
    base = Path(root) / MAIN
    names = dict(re.findall(r'^\s*([A-Z_0-9]+)\("([^"]+)"\)', (base / "content/data/Quests.kt").read_text(), re.M))
    index = {}
    for f in list(base.rglob("*.kt")) + list(base.rglob("*.java")):
        for enum, i in re.findall(r"\b(?:Quest|super)\(\s*Quests\.([A-Z_0-9]+)\s*,\s*(\d+)\s*,\s*\d+\s*,\s*\d+", f.read_text(errors="ignore")):
            if enum in index and index[enum] != int(i):
                raise SystemExit(f"quest {enum} declared with two indexes")
            index[enum] = int(i)
    unknown = sorted(set(index) - set(names))
    if unknown:
        raise SystemExit(f"quest classes without a Quests.kt name: {unknown}")
    by_id = {}
    for enum, i in index.items():
        if i in by_id:
            raise SystemExit(f"quest index {i} used twice: {by_id[i]} and {enum}")
        by_id[i] = names[enum]
    return dict(sorted(by_id.items()))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source-root", required=True)
    ap.add_argument("--source-commit", required=True)
    ap.add_argument("--output", default="site/js/services/quest-ids.js")
    a = ap.parse_args()
    table = parse(a.source_root)
    if len(table) < 60:
        raise SystemExit(f"only {len(table)} quests parsed; source layout changed?")
    body = ",\n".join(f"  {i}: {json.dumps(n, ensure_ascii=False)}" for i, n in table.items())
    Path(a.output).write_text(
        f"// GENERATED by data-pipeline/generate_quest_ids.py from 2009Scape {a.source_commit}. Do not edit by hand.\n"
        f"// Key = Quest.index, the questId stored in player saves.\n"
        f"export const QUEST_NAMES = {{\n{body}\n}};\n")
    print(f"wrote {len(table)} quests to {a.output}")


if __name__ == "__main__":
    main()
