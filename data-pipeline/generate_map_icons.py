#!/usr/bin/env python3
"""Clickable map-icon spots from the 2009Scape (RS #530) cache -> site/data/map/icons.js.

The map tiles carry the little picture icons (bank, altar, anvil ...) baked into the image. This lists where the matching
objects stand in the 2009 landscape files so each icon can be tapped for a description. Objects of one kind within 9 tiles of
each other on the same floor (the booths of one bank, say) become one spot at their centre.
usage: generate_map_icons.py [--cache DIR]   (DIR holds cache/ and configs/xteas.json; default is mapgen's CACHE_DIR)
"""
import json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent / "mapgen"))
from cache import Cache
from world import CACHE_DIR, parse_locs, load_xteas
from objects import Objects

KINDS = {  # object name (lower case) -> (label, what it is for)
    "bank booth": ("Bank", "Store and withdraw items."), "bank chest": ("Bank", "Store and withdraw items."),
    "bank deposit box": ("Deposit box", "Deposit items to your bank without withdrawing."),
    "altar": ("Altar", "Pray here to restore Prayer points."), "chaos altar": ("Chaos altar", "Offer bones here for Prayer experience."),
    "anvil": ("Anvil", "Smith bars into weapons and armour with a hammer."), "barbarian anvil": ("Anvil", "Smith bars into weapons and armour with a hammer."),
    "furnace": ("Furnace", "Smelt ores into bars and make jewellery."), "small furnace": ("Furnace", "Smelt ores into bars and make jewellery."),
    "range": ("Cooking range", "Cook food with a lower chance of burning."), "cooking range": ("Cooking range", "Cook food with a lower chance of burning."),
    "spinning wheel": ("Spinning wheel", "Spin wool, flax and other fibres into thread."),
    "potter's wheel": ("Potter's wheel", "Shape soft clay into unfired pottery."), "pottery oven": ("Pottery oven", "Fire unfired pottery."),
    "loom": ("Loom", "Weave items such as sacks and baskets."),
}
RADIUS = 9

root = Path(sys.argv[sys.argv.index("--cache") + 1]) if "--cache" in sys.argv else CACHE_DIR
c = Cache(root / "cache"); xt = load_xteas(root / "configs/xteas.json"); OBJ = Objects(c)
found = {}
for rx in range(0, 60):
    for ry in range(0, 200):
        lg = c.group_by_name(5, f"l{rx}_{ry}")
        if lg is None: continue
        try: locs = parse_locs(next(iter(c.files(5, lg, xt.get((rx << 8) | ry)).values())))
        except Exception: continue
        for oid, typ, rot, x, y, plane in locs:
            d = OBJ.get(oid)
            kind = KINDS.get(d["name"].strip().lower())
            if not kind: continue
            sx, sy = (d["sx"], d["sy"]) if rot % 2 == 0 else (d["sy"], d["sx"])
            found.setdefault((kind[0], plane), set()).add((rx * 64 + x + (sx - 1) / 2, ry * 64 + y + (sy - 1) / 2))

desc = {v[0]: v[1] for v in KINDS.values()}
spots = []
for (label, plane), pts in sorted(found.items()):
    groups = []
    for p in sorted(pts):
        for g in groups:
            if any(max(abs(p[0] - q[0]), abs(p[1] - q[1])) <= RADIUS for q in g): g.append(p); break
        else: groups.append([p])
    # merge groups that grew together
    merged = True
    while merged:
        merged = False
        for i in range(len(groups)):
            for j in range(i + 1, len(groups)):
                if any(max(abs(a[0] - b[0]), abs(a[1] - b[1])) <= RADIUS for a in groups[i] for b in groups[j]):
                    groups[i] += groups.pop(j); merged = True; break
            if merged: break
    for g in groups:
        spots.append({"name": label, "x": round(sum(p[0] for p in g) / len(g), 1), "y": round(sum(p[1] for p in g) / len(g), 1), "plane": plane})
spots.sort(key=lambda r: (r["name"], r["plane"], r["y"], r["x"]))
meta = {"source": "2009Scape cache (RS #530) object placements", "count": len(spots), "descriptions": desc}
out = Path(__file__).resolve().parents[1] / "site/data/map/icons.js"
out.write_text("// Generated by data-pipeline/generate_map_icons.py from the 2009Scape cache. Do not edit by hand.\n"
               f"window.OSRS_MAP_ICON_META = {json.dumps(meta, ensure_ascii=False)};\n"
               f"window.OSRS_MAP_ICONS = {json.dumps(spots, ensure_ascii=False, separators=(',', ':'))};\n", encoding="utf-8")
from collections import Counter
print(len(spots), "spots", dict(Counter(s["name"] for s in spots)), out.stat().st_size, "bytes")
